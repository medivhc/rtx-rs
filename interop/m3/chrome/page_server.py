"""Tiny static HTTPS server for the WebTransport capture client page.

Chrome refuses `new WebTransport(...)` from a `file://` page origin in this
setup, so the page is served over HTTPS from a separate origin. The
certificate is the runtime self-signed one generated by run.sh (the same
certificate Chrome is told to accept through --ignore-certificate-errors-spki-list).

Usage: page_server.py <port> <cert.pem> <key.pem>
"""

import http.server
import os
import ssl
import sys

port = int(sys.argv[1])
cert = sys.argv[2]
key = sys.argv[3]

# Serve index.html from this harness directory regardless of the caller's cwd.
os.chdir(os.path.dirname(os.path.abspath(__file__)))

server = http.server.ThreadingHTTPServer(("127.0.0.1", port), http.server.SimpleHTTPRequestHandler)
context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
context.load_cert_chain(cert, key)
server.socket = context.wrap_socket(server.socket, server_side=True)
print("serving on", port, flush=True)
server.serve_forever()
